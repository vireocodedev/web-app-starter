const arch = (name, trigger, owners, aliases = []) => ({
  key: architecture(name),
  aliases,
  scope: "frontend",
  kind: "contract",
  status: "installed pattern",
  path: `frontend/docs/architecture/en/${name}.md`,
  counterpart: `frontend/docs/architecture/hr/${name}.md`,
  trigger,
  owners,
  checks,
  requires: ["frontend-baseline"],
});
const tutorial = (key, relative, trigger, requires = [], options = {}) => ({
  key,
  scope: "frontend",
  kind: "tutorial",
  status: "installed + reference recipe",
  path: `frontend/docs/storybook/${relative}.mdx`,
  trigger,
  requires: ["frontend-baseline", ...requires],
  owners: ["frontend/docs/storybook", app],
  checks,
  ...options,
});
const procedure = (key, name, trigger, requires) => ({
  key,
  scope: "frontend",
  kind: "skill",
  status: "procedure",
  path: `frontend/.agents/skills/${name}/SKILL.md`,
  trigger,
  requires,
  owners: [app],
  checks,
});

